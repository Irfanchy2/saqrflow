  await p.goto(`${BASE}/invoices?tab=invoice`); await settle()
  ok((await body()).includes(inv.number) && (await body()).includes('Paid'), 'invoice listed with status')
  await p.goto(`${BASE}/invoices?tab=payments`); await settle()
  ok((await body()).includes('TT-7781') && (await body()).includes('20,000.00'), 'payments tab lists both payments')
  const cid = (await one(`select id from customers where company_id=$1 and name='ABC Contracting LLC'`, [co])).id
  await p.goto(`${BASE}/parties/${cid}`); await settle()
  ok((await body()).includes(qnum) && (await body()).includes(inv.number) && (await body()).includes('Received (all time)'), 'customer profile: documents and money received')
  await shot('31-customer-profile')

  console.log('\n[S6] Projects')
  await p.goto(`${BASE}/projects`); await p.getByRole('button', { name: 'New project' }).click()
  await dlg().getByLabel('Project name *').fill('Villa 22 staircase & canopy'); await dlg().getByLabel('Client').selectOption(cid)
  await dlg().getByLabel('Contract value (AED)').fill('100000'); await dlg().getByLabel('Status').selectOption('active')
  await dlg().getByRole('button', { name: 'Create project' }).click(); await p.waitForURL(/\/projects\/[0-9a-f-]{36}$/); await settle()
  const pid = p.url().split('/').pop()
  await p.getByRole('button', { name: 'Add' }).first().click(); await dlg().getByLabel('Milestone *').fill('Delivery to site'); await dlg().getByRole('button', { name: 'Add milestone' }).click(); await settle(900)
  await p.getByRole('button', { name: 'Add' }).nth(1).click(); await dlg().getByLabel('Description *').fill('MS hollow section 100×50×3'); await dlg().getByLabel('Amount (AED) *').fill('12000'); await dlg().getByRole('button', { name: 'Add cost' }).click(); await settle(900)

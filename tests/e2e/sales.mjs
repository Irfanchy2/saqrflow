  await p.getByRole('button', { name: 'Upload' }).click(); await dlg().locator('input[type=file]').setInputFiles({ name: 'shop-drawing.pdf', mimeType: 'application/pdf', buffer: pdfBuf }); await dlg().getByRole('button', { name: 'Upload' }).click(); await settle(1500)
